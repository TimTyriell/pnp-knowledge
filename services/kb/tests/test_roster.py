"""In-world roster (T8): roster.yaml -> Character frontmatter."""

from __future__ import annotations

import sys
from pathlib import Path

import yaml
from pnp_okf.emit import emit_entity
from pnp_okf.episodes import Episodes
from pnp_okf.models import CanonicalEntity, EntityType, MentionRef
from pnp_okf.okf import split_document
from pnp_okf.roster import load_roster

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from sync_roster import build_roster, render  # noqa: E402


def _write_roster(knowledge: Path, rows: list[dict]) -> None:
    knowledge.mkdir(parents=True, exist_ok=True)
    (knowledge / "roster.yaml").write_text(
        yaml.safe_dump({"characters": rows}, allow_unicode=True), encoding="utf-8"
    )


def test_load_roster_maps_fields_and_drops_nulls(tmp_path: Path):
    _write_roster(tmp_path, [
        {"name": "Lindo Laut", "concept_id": "characters/lindo_laut", "team": "A",
         "class": "Fee Barde", "since": None, "until": None},
        {"name": "Ada", "concept_id": "characters/ada", "team": "B",
         "class": "Krieger", "since": "2026-01-01", "until": "2026-06-01"},
    ])
    roster = load_roster(tmp_path)
    assert roster["characters/lindo_laut"] == {"team": "A", "class": "Fee Barde"}
    assert roster["characters/ada"] == {
        "team": "B", "class": "Krieger",
        "active_since": "2026-01-01", "active_until": "2026-06-01",
    }


def test_load_roster_skips_unmatched_and_non_character_rows(tmp_path: Path):
    _write_roster(tmp_path, [
        {"name": "Niemand", "concept_id": None, "team": "A", "class": "X"},
        {"name": "Burg", "concept_id": "locations/burg", "team": "A", "class": "X"},
    ])
    assert load_roster(tmp_path) == {}


def test_load_roster_absent_file_is_empty(tmp_path: Path):
    assert load_roster(tmp_path) == {}


def test_build_roster_matches_name_alias_slug_and_sorts(tmp_path: Path):
    registry = {"entities": [
        {"concept_id": "characters/lindo_laut", "type": "Character",
         "canonical_name": "Lindo Laut", "aliases": []},
        {"concept_id": "characters/mikos_dodo", "type": "Character",
         "canonical_name": "Dodo", "aliases": ["Dodo Goblin"]},
        {"concept_id": "locations/dodo_haus", "type": "Location",
         "canonical_name": "Dodo Haus", "aliases": []},
    ]}
    export = [
        {"name": "Dodo Goblin", "class": "Halb-Goblin", "group": "Team-B",
         "since": None, "until": None},
        {"name": "lindo laut", "class": "Fee Barde", "group": "Team-A",
         "since": None, "until": None},
        {"name": "Unbekannt", "class": "Zauberer", "group": "Team-A",
         "since": None, "until": None},
    ]
    episodes = Episodes(teams={"Team-A": "A", "Team-B": "B"})
    rows = build_roster(export, registry, episodes)
    assert [(r["name"], r["concept_id"], r["team"]) for r in rows] == [
        ("lindo laut", "characters/lindo_laut", "A"),
        ("Unbekannt", None, "A"),
        ("Dodo Goblin", "characters/mikos_dodo", "B"),
    ]
    # Ids are never invented: an unmatched name stays null.
    assert rows[1]["concept_id"] is None


def test_render_has_generated_header_and_round_trips(tmp_path: Path):
    rows = [{"name": "Lindo Laut", "concept_id": "characters/lindo_laut",
             "team": "A", "class": "Fee Barde", "since": None, "until": None}]
    text = render(rows)
    assert text.startswith("# GENERATED by services/kb/sync_roster.py")
    assert yaml.safe_load(text)["characters"] == rows


def _entity(mtype: EntityType, cid: str) -> CanonicalEntity:
    return CanonicalEntity(
        concept_id=cid, type=mtype, canonical_name="Testo",
        mentions=[MentionRef(session_id="s1", date="2026-01-01", url="http://x",
                             citation_ts="00:01:00", note="Ein Testling.")],
    )


def test_emit_entity_writes_extra_frontmatter(tmp_path: Path):
    emit_entity(
        tmp_path, _entity(EntityType.CHARACTER, "characters/testo"),
        "# Überblick\n\nText.\n\n# Belege\n\n[1] x",
        extra_frontmatter={"team": "A", "class": "Fee Barde"},
    )
    fm, _ = split_document((tmp_path / "characters" / "testo.md").read_text(encoding="utf-8"))
    assert fm["team"] == "A"
    assert fm["class"] == "Fee Barde"
    assert "team" not in _frontmatter_of_npc(tmp_path)


def _frontmatter_of_npc(tmp_path: Path) -> dict:
    emit_entity(tmp_path, _entity(EntityType.NPC, "npcs/testo"),
                "# Überblick\n\nText.\n\n# Belege\n\n[1] x")
    fm, _ = split_document((tmp_path / "npcs" / "testo.md").read_text(encoding="utf-8"))
    return fm
