"""In-world roster fields for Character concepts (T8).

``knowledge/roster.yaml`` is generated by ``services/kb/sync_roster.py`` from
pnp-crawl's roster export. It holds in-world facts only (no player names).
"""

from __future__ import annotations

from pathlib import Path

import yaml


def load_roster(knowledge_root: Path) -> dict[str, dict]:
    """``concept_id -> {team, class, active_since, active_until}`` from roster.yaml.

    Rows with no matched concept id are skipped, and so are ids outside
    ``characters/``: roster fields only ever belong on Character concepts.
    An absent file means no roster yet (before the HUMAN RUN), not an error.
    """
    path = knowledge_root / "roster.yaml"
    if not path.is_file():
        return {}
    data = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    out: dict[str, dict] = {}
    for row in data.get("characters") or []:
        cid = row.get("concept_id")
        if not cid or not str(cid).startswith("characters/"):
            continue
        fields = {
            "team": row.get("team"),
            "class": row.get("class"),
            "active_since": row.get("since"),
            "active_until": row.get("until"),
        }
        out[str(cid)] = {k: v for k, v in fields.items() if v is not None}
    return out
