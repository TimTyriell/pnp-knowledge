"""Write knowledge/roster.yaml from pnp-crawl's in-world roster export (T8).

The export comes from pnp-crawl's ``export_roster.py`` (plan C4):

    [{"name": "Lindo Laut", "class": "Fee Barde",
      "group": "Team-A", "since": null, "until": null}]

A top-level list, one row per character stint (``roster_rows`` there).

Only in-world facts are written. Player names stay in the private export and
are never copied here. A character whose name matches no Character concept in
entity_registry.yaml gets ``concept_id: null`` and is listed on stderr: ids
are never invented. Fix those with a ``merge:`` or ``canonical_name:`` rule.

    python sync_roster.py                 # writes knowledge/roster.yaml
    python sync_roster.py --check         # exit 1 if the file would change
    python sync_roster.py --from <path>   # another export file
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import yaml
from pnp_okf.episodes import Episodes
from pnp_okf.okf import slugify

ROOT = Path(__file__).resolve().parent  # services/kb
KNOWLEDGE = ROOT.parent.parent / "knowledge"
REGISTRY = KNOWLEDGE / "entity_registry.yaml"
EPISODES = KNOWLEDGE / "episodes.yaml"
OUT = KNOWLEDGE / "roster.yaml"
# Sibling of this repo: pnp-knowledge/services/kb -> lindo-lauts-notebook/pnp-crawl.
DEFAULT_FROM = ROOT.parents[2] / "pnp-crawl" / "groups" / "roster_public.json"

HEADER = (
    "# GENERATED by services/kb/sync_roster.py from pnp-crawl's roster export.\n"
    "# In-world facts only -- no player names (docs/plans/T00 D1).\n"
)


def match_concept(name: str, characters: list[dict]) -> str | None:
    """Concept id of the Character named *name*: canonical name, then alias
    (both case-insensitive), then slug. None when nothing matches."""
    key = name.strip().lower()
    for e in characters:
        if str(e.get("canonical_name") or "").strip().lower() == key:
            return e["concept_id"]
    for e in characters:
        if any(str(a).strip().lower() == key for a in e.get("aliases") or []):
            return e["concept_id"]
    slug = slugify(name)
    for e in characters:
        names = [str(e.get("canonical_name") or ""), *map(str, e.get("aliases") or [])]
        if any(slugify(n) == slug for n in names):
            return e["concept_id"]
    return None


def build_roster(export: list[dict], registry: dict, episodes: Episodes) -> list[dict]:
    """Roster rows sorted by (team, name). Pure: no I/O."""
    characters = [e for e in registry.get("entities") or [] if e.get("type") == "Character"]
    rows = [
        {
            "name": c["name"],
            "concept_id": match_concept(c["name"], characters),
            "team": episodes.team_letter(c.get("group")),
            "class": c.get("class"),
            "since": c.get("since"),
            "until": c.get("until"),
        }
        for c in export
    ]
    rows.sort(key=lambda r: (r["team"] or "", r["name"].casefold()))
    return rows


def render(rows: list[dict]) -> str:
    return HEADER + yaml.safe_dump({"characters": rows}, allow_unicode=True, sort_keys=False)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Write knowledge/roster.yaml from the roster export.")
    ap.add_argument("--from", dest="source", type=Path, default=DEFAULT_FROM)
    ap.add_argument("--check", action="store_true", help="exit 1 if roster.yaml would change")
    args = ap.parse_args(argv)

    export = json.loads(args.source.read_text(encoding="utf-8"))
    registry = yaml.safe_load(REGISTRY.read_text(encoding="utf-8")) or {}
    rows = build_roster(export, registry, Episodes.load(EPISODES))
    for row in rows:
        if row["concept_id"] is None:
            print(f"unmatched (concept_id: null): {row['name']}", file=sys.stderr)

    text = render(rows)
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT} is out of date; run sync_roster.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT} ({len(rows)} characters)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
