test('restores history while retaining the later saved version', async ({ page, server, request }) => {
  await createCampaign(page)
  const original = await savedWorkspace(request, server.url)
  await addEntry(page, 'Runa', 'The keeper.')
  const edited = await savedWorkspace(request, server.url)
  await section(page, 'History').click()
  page.once('dialog', dialog => dialog.accept())
  const initialRevision = page.getByRole('listitem').filter({ has: page.getByText('Campaign created', { exact: true }) })
  const restoring = page.waitForResponse(response => response.url().endsWith('/restore') && response.request().method() === 'POST')
  await initialRevision.getByRole('button', { name: 'Restore this version', exact: true }).click()
  expect((await restoring).ok()).toBeTruthy()
  const restored = await savedWorkspace(request, server.url)
  expect(restored.entries).toHaveLength(0)
  expect(restored.history.map(row => row.revision)).toEqual([original.revision, edited.revision, restored.revision])
  expect(restored.revision).not.toBe(original.revision)
  await page.reload()
  await openCampaign(page, 'Moonfall')
  await expect(page.getByText('Your campaign starts here.', { exact: false })).toBeVisible()
})

test('downloads and imports a portable bundle with its relationships', async ({ page, server, request }, testInfo) => {
  await createCampaign(page)
  await addEntry(page, 'Moonfall Pier', 'A quiet landing.', 'Location')
  await addEntry(page, 'Runa', 'Keeper of the pier.', 'NPC', 'Moonfall Pier')
  const original = await savedWorkspace(request, server.url)
  const downloadEvent = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export bundle', exact: true }).click()
  const download = await downloadEvent
  const path = testInfo.outputPath('moonfall.zip')
  await download.saveAs(path)
  expect(await download.failure()).toBeNull()
  await page.getByRole('button', { name: /All campaigns/ }).click()
  const form = page.locator('form').filter({ has: page.getByRole('button', { name: 'Import campaign', exact: true }) })
  await form.getByLabel('Campaign name', { exact: true }).fill('Reopened Moonfall')
  await form.getByLabel('Choose a campaign bundle ZIP', { exact: true }).setInputFiles(path)
  const importedResponse = page.waitForResponse(response => response.url().includes('/api/workspaces/import') && response.request().method() === 'POST')
  await form.getByRole('button', { name: 'Import campaign', exact: true }).click()
  const response = await importedResponse
  expect(response.ok()).toBeTruthy()
  await expect(page.getByRole('heading', { name: 'Reopened Moonfall', exact: true })).toBeVisible()
  const campaigns = await request.get(`${server.url}/api/workspaces`).then(result => result.json()) as { id: string; name: string }[]
  const imported = campaigns.find(campaign => campaign.name === 'Reopened Moonfall')!
  expect((await savedWorkspace(request, server.url, imported.id)).entries).toEqual(original.entries)
})

