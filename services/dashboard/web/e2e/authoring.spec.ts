import { test, expect } from './fixtures.ts'
import { addEntry, createCampaign, entryList, openCampaign, savedWorkspace, section } from './actions.ts'

test('authors linked entries, edits and reopens saved content', async ({ page, server, request }) => {
  await createCampaign(page)
  await addEntry(page, 'Moonfall Pier', 'A quiet landing.', 'Location')
  await addEntry(page, 'Runa', 'Keeper of the pier.', 'NPC', 'Moonfall Pier')
  await entryList(page).getByRole('button', { name: /^Runa/ }).click()
  await page.getByRole('button', { name: 'Edit entry', exact: true }).click()
  await page.getByLabel('Description and notes', { exact: true }).fill('GM correction: Runa owns the pier.')
  await page.getByRole('button', { name: 'Save entry', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Save entry', exact: true })).toHaveCount(0)
  await page.reload()
  await openCampaign(page, 'Moonfall')
  await entryList(page).getByRole('button', { name: /^Runa/ }).click()
  await expect(page.getByText('GM correction: Runa owns the pier.', { exact: true })).toBeVisible()
  const workspace = await savedWorkspace(request, server.url)
  const pier = workspace.entries.find(entry => entry.title === 'Moonfall Pier')!
  expect(workspace.entries.find(entry => entry.title === 'Runa')).toMatchObject({ body: 'GM correction: Runa owns the pier.', related: [pier.concept] })
})

