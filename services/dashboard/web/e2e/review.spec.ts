import { test, expect } from './fixtures.ts'
import { entryList, openCampaign, proposal, savedWorkspace, section } from './actions.ts'

test.use({ scenario: 'review' })

test('reviews evidence, edits an update and rejects an addition through the real API', async ({ page, server, request }) => {
  await openCampaign(page)
  await section(page, 'Review').click()
  const mara = proposal(page, 'Mara')
  await mara.getByText('Read full source evidence', { exact: true }).click()
  await expect(mara.getByText(/Mara helped the party escape/)).toBeVisible()
  await mara.getByLabel('Suggested note for Mara', { exact: true }).fill('Opened the cellar door.')
  await mara.getByRole('button', { name: 'Accept suggestion', exact: true }).click()
  await proposal(page, 'Muddy Coin').getByRole('button', { name: 'Reject', exact: true }).click()
  await page.getByRole('button', { name: 'Apply selected decisions', exact: true }).click()
  await expect(mara).toHaveCount(0)
  const workspace = await savedWorkspace(request, server.url, server.seedId)
  expect(workspace.entries.find(entry => entry.title === 'Mara')?.body).toContain('GM ruling: Mara owns the inn.')
  expect(workspace.entries.find(entry => entry.title === 'Mara')?.body).toContain('Opened the cellar door.')
  expect(workspace.entries.find(entry => entry.title === 'Mara')?.body).toContain('Session one')
  expect(workspace.entries.some(entry => entry.title === 'Muddy Coin')).toBeFalsy()
  expect(workspace.proposals.find(item => item.title === 'Muddy Coin')?.status).toBe('rejected')
  await page.reload()
  await openCampaign(page)
  await entryList(page).getByRole('button', { name: /^Mara/ }).click()
  await expect(page.getByText('Opened the cellar door.', { exact: false })).toBeVisible()
})

test('bulk acceptance skips rejections and unresolved identities until explicitly selected', async ({ page, server, request }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await openCampaign(page)
  await section(page, 'Review').click()
  const ambiguous = proposal(page, 'Copper Towr')
  await ambiguous.getByRole('button', { name: 'Accept suggestion', exact: true }).click()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  await expect(page.getByRole('button', { name: 'Apply selected decisions', exact: true })).toHaveCount(0)
  await proposal(page, 'Muddy Coin').getByRole('button', { name: 'Reject', exact: true }).click()
  await proposal(page, 'Glass Bell').getByLabel('Suggested note for Glass Bell', { exact: true }).fill('It rings only at dawn.')
  await page.getByRole('button', { name: 'Accept clear new entries', exact: true }).click()
  await expect(proposal(page, 'Glass Bell')).toHaveCount(0)
  const bulk = await savedWorkspace(request, server.url, server.seedId)
  expect(bulk.entries.find(entry => entry.title === 'Glass Bell')?.body).toContain('It rings only at dawn.')
  expect(bulk.entries.some(entry => entry.title === 'Muddy Coin' || entry.title === 'Copper Towr')).toBeFalsy()
  expect(bulk.proposals.find(item => item.title === 'Copper Towr')?.status).toBe('pending')
  expect(bulk.proposals.find(item => item.title === 'Muddy Coin')?.status).toBe('pending')
  await ambiguous.getByLabel('Apply this note to', { exact: true }).selectOption('__new')
  await page.getByRole('button', { name: 'Apply selected decisions', exact: true }).click()
  await expect(ambiguous).toHaveCount(0)
  const selected = await savedWorkspace(request, server.url, server.seedId)
  expect(selected.entries.find(entry => entry.title === 'Copper Towr')?.body).toContain('A hidden cellar lies beneath it.')
  expect(selected.proposals.find(item => item.title === 'Muddy Coin')?.status).toBe('rejected')
  expect(selected.entries.filter(entry => entry.title.startsWith('Copper'))).toHaveLength(3)
})
